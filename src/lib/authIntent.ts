/* authIntent — "เขาตั้งใจมาสมัคร แต่ล็อกอินค้างอยู่คนละบัญชี" ต้องบอกเสมอ ห้ามเงียบ
 *
 * 🔴 บั๊กจริง (พบ 19 ส.ค. 2569): ลิงก์ `?enter=auth` ถูกอ่านอยู่ "ข้างใน" เงื่อนไข `!session`
 *   ⇒ ถ้าเบราว์เซอร์ยังมี session ค้าง ลิงก์สมัครสมาชิกจะเงียบสนิท แล้วเด้งเข้า Dashboard
 *     ของบัญชีเดิม โดยไม่บอกสักคำว่ากำลังล็อกอินเป็นใคร
 *   เกิดขึ้นจริง: เจ้าของระบบกดลิงก์เพื่อทดสอบสมัครด้วยอีเมลใหม่ → เห็น Dashboard เต็มไปด้วย
 *     ความคืบหน้า 83% → เข้าใจว่าสมัครสำเร็จ ทั้งที่ฐานข้อมูลไม่มีบัญชีใหม่เลยสักแถว
 *
 * เรื่องเดียวกับบั๊ก RLS ที่เจอวันเดียวกัน: **หน้าจอดูปกติ ทั้งที่สถานะจริงไม่ใช่อย่างที่คิด**
 * pure ทั้งไฟล์
 */

export interface AuthIntentState {
  /** ผู้ใช้เข้ามาด้วยลิงก์ที่ตั้งใจจะ "สมัคร/เข้าสู่ระบบ" (`?enter=auth`)
   *  ⚠️ ต้องเป็นค่าที่ latch ไว้ตอน mount — query ถูกล้างทิ้งทันทีหลัง mount เพื่อให้ URL สะอาด */
  cameForAuth: boolean;
  /** ตอนนี้มี session ค้างอยู่ไหม */
  hasSession: boolean;
  /** ผู้ใช้กด "ใช้บัญชีนี้ต่อ" แล้ว */
  dismissed: boolean;
}

/** ต้องขึ้นแถบเตือน "คุณล็อกอินอยู่คนละบัญชี" หรือไม่
 *  เงื่อนไขสำคัญคือ **hasSession = true** — ตรงข้ามกับที่โค้ดเดิมเช็ค (`!session`)
 *  ซึ่งคือเหตุผลที่บั๊กนี้เกิด */
export function shouldWarnWrongAccount(s: AuthIntentState): boolean {
  return s.cameForAuth && s.hasSession && !s.dismissed;
}

/** ข้อความบอกว่าตอนนี้เป็นใคร — ต้องมีตัวตนที่ตรวจสอบได้เสมอ ห้ามพูดลอย ๆ ว่า "คุณล็อกอินอยู่" */
export function wrongAccountText(email: string | null | undefined): string {
  return email
    ? `คุณกำลังใช้งานในชื่อ ${email} — ลิงก์สมัครสมาชิกจึงพาเข้าบัญชีนี้แทน`
    : 'คุณกำลังใช้งานในบัญชีเดิมอยู่ — ลิงก์สมัครสมาชิกจึงพาเข้าบัญชีนี้แทน';
}
