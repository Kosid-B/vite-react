/** เรื่องที่ควรขึ้นก่อน + เหตุผลที่อ้างได้จาก "ตัวเลขของเขาเอง" เท่านั้น
 *  คืน null เมื่อข้อมูลที่กรอกยังไม่พอจะชี้ — ห้ามเดาแทน */
export interface NextFocus { id: string; why: string }

export function focusFor(r: QuickResult): NextFocus | null {
  const verdict = verdictOf(r);

  // ขาดทุนรวมทั้งเดือน ทั้งที่กำไรต่อชิ้นเป็นบวก ⇒ ตัวปัญหาคือรายจ่ายคงที่/วิธีทำงาน ไม่ใช่ราคา
  if (verdict === 'netLoss') {
    return { id: 'system', why: 'กำไรต่อชิ้นเป็นบวก แต่รวมทั้งเดือนยังติดลบ — ตัวที่กินคือรายจ่ายประจำกับเวลาที่หมดไปกับงานซ้ำ ๆ' };
  }
  // ยังไม่ถึงจุดคุ้มทุน และรู้ว่าขาดอีกกี่ชิ้น ⇒ เรื่องถัดไปคือ "ขายให้ได้เพิ่ม"
  if (r.unitsToBreakEven !== null && r.unitsToBreakEven > 0) {
    return { id: 'customers', why: `ยังขาดอีก ${r.unitsToBreakEven.toLocaleString('th-TH')} ชิ้น/เดือนถึงจะคุ้มทุน — เรื่องถัดไปคือหาคนซื้อเพิ่ม ไม่ใช่ลดต้นทุนอีก` };
  }
  // กำไรต่อชิ้นติดลบ ⇒ ยังอยู่ที่เรื่องโครงสร้างต้นทุน/วิธีทำ
  if (verdict === 'loss') {
    return { id: 'system', why: 'ขายชิ้นนึงแล้วยังติดลบ — ต้องไปดูที่โครงสร้างต้นทุนกับวิธีทำงานก่อน' };
  }
  // ผ่านจุดคุ้มทุนแล้ว ⇒ เรื่องถัดไปคือให้คนหาเจอมากขึ้น
  if (r.unitsToBreakEven === 0 && (verdict === 'ok' || verdict === 'thin')) {
    return { id: 'found', why: 'ผ่านจุดคุ้มทุนแล้ว — เรื่องถัดไปคือทำให้คนที่กำลังมองหาของแบบนี้ เจอร้านคุณ' };
  }
  return null;   // ข้อมูลไม่พอจะชี้ — แสดงรายการตามลำดับปกติ ไม่เดาให้
}

/** รายการที่จัดลำดับตามตัวเลขของเขา — ไม่ตัดเรื่องไหนทิ้ง ย้ายขึ้นอย่างเดียว */
export function nextProblemsFor(r: QuickResult): readonly NextProblem[] {
  const focus = focusFor(r);
  if (!focus) return NEXT_PROBLEMS;
  const first = NEXT_PROBLEMS.find((p) => p.id === focus.id);
  if (!first) return NEXT_PROBLEMS;
  return [first, ...NEXT_PROBLEMS.filter((p) => p.id !== focus.id)];
}

/** พาดหัวของบล็อก — จำนวนนับจากรายการจริง ไม่ใช่เลขที่พิมพ์ไว้ตายตัว */
export function nextProblemsHeading(): string {
  return `เรื่องต้นทุนจบแล้ว — ยังเหลืออีก ${NEXT_PROBLEMS.length} เรื่องที่ทำให้ร้านไม่โต`;
}
