/** ข้อ ISO ที่ "ไม่มีคู่" ใน MIT 24 — ต้องสร้างใหม่ตอนทำระบบมาตรฐาน
 *  สำคัญ: ใช้บอกลูกค้าตรง ๆ ว่าทำ MIT แล้วยังเหลืออะไร ไม่ใช่ขายว่าทำอันเดียวได้ทั้งสอง */
export const ISO_ONLY_CLAUSES = [
  '5.1', '5.3',        // ความมุ่งมั่นผู้บริหาร · บทบาทหน้าที่
  '7.1', '7.2', '7.3', '7.4', '7.5', // ทรัพยากร ความสามารถ ความตระหนัก สื่อสาร ควบคุมเอกสาร
  '8.3', '8.4', '8.5', '8.6', '8.7', // ออกแบบ ผู้ขายภายนอก ควบคุมผลิต ตรวจปล่อย ของไม่ผ่าน
  '9.2', '9.3',        // ตรวจติดตามภายใน · ทบทวนฝ่ายบริหาร
  '10.2',              // แก้ไขที่รากเหง้า
] as const;

/** ข้อ ISO ที่ได้ประโยชน์จากข้อมูล MIT 24 ที่ทำไว้แล้ว */
export function isoClausesCoveredByDe24(): string[] {
  return [...new Set(LADDER.flatMap((l) => l.isoClauses))].sort();
}

/** ขั้น MIT 24 ที่ข้อมูลถูกนำไปใช้ต่อในระบบมาตรฐาน */
export function de24StepsFeedingIso(): number[] {
  return [...new Set(LADDER.flatMap((l) => l.de24))].sort((a, b) => a - b);
}

/** ประเมินว่าถ้าทำ MIT 24 ไปแล้ว n ขั้น จะช่วยลดงานทำ ISO ได้แค่ไหน (หยาบ ๆ แต่ซื่อสัตย์)
 *  คืนสัดส่วนของ "ข้อที่มีข้อมูลตั้งต้นแล้ว" เทียบข้อ ISO ทั้งหมดที่ต้องทำ */
export function headStartFromDe24(doneSteps: readonly number[]): {
  clausesWithHeadStart: string[];
  totalIsoClauses: number;
  pct: number;
} {
  const done = new Set(doneSteps);
  const clauses = new Set<string>();
  for (const link of LADDER) {
    if (link.de24.some((s) => done.has(s))) link.isoClauses.forEach((c) => clauses.add(c));
  }
  const total = new Set([...isoClausesCoveredByDe24(), ...ISO_ONLY_CLAUSES]).size;
  const list = [...clauses].sort();
  return {
    clausesWithHeadStart: list,
    totalIsoClauses: total,
    pct: total === 0 ? 0 : Math.round((list.length / total) * 100),
  };
}

/** หาสะพานจากข้อ ISO — ใช้ตอบว่า "ข้อนี้เอาข้อมูลจากไหนมาได้บ้าง" */
export function ladderForClause(clauseId: string): LadderLink | undefined {
  return LADDER.find((l) => l.isoClauses.includes(clauseId));
}
