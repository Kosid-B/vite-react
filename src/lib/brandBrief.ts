/** ⑥ คำที่ห้ามใช้เด็ดขาด — ชุดเดียวกับที่ landingClaims.test.ts เฝ้าหน้าเว็บอยู่
 *  (ถ้าวันหนึ่งระบบทำได้จริง ให้ลบพร้อมกันทั้งสองที่) */
