/** ⑦ สถานะจริงตอนนี้ — ช่องที่ Brand Brief ทั่วไป "ไม่มี" และเป็นช่องที่สำคัญที่สุดของเรา
 *
 *  เพราะ brief ที่เล่าแต่ภาพฝัน จะทำให้ AI เขียนคอนเทนต์ที่อ้างการยอมรับที่เรายังไม่มี
 *  (เช่น "ลูกค้าหลายร้อยราย") — ซึ่งเป็นการโกหกที่ตรวจจับยากที่สุด เพราะฟังดูปกติมาก
 *  ⚠️ ตัวเลขในนี้ต้องอัปเดตเมื่อของจริงเปลี่ยน · อ่านสดได้จาก stageFit + payingCustomerCount */
export const HONEST_STATE = {
  payingCustomers: 'ยังไม่มีลูกค้าที่จ่ายเงินจริงสักราย (รายการซื้อทั้งหมดเป็นการเปิดให้ฟรีโดยแอดมิน)',
  reach: 'ผู้เข้าชมเว็บสะสมตลอดกาลอยู่ในหลักสิบ ไม่ใช่หลักพัน',
  implication: 'ห้ามเขียนอะไรที่อ้างจำนวนลูกค้า ยอดขาย หรือการยอมรับในตลาด · ให้ขายด้วย "สิ่งที่ระบบทำได้" เท่านั้น',
} as const;

/** ⑧ ประกอบเป็นบล็อกบริบทสำหรับแปะหน้า prompt
 *  = กล่อง "บริษัท/ปัญหา/ความต้องการ/ผลลัพธ์" ในแผนภาพ Brand Brief
 *
 *  @param opts.forPublicCopy true = กำลังจะเขียนข้อความที่คนนอกเห็น ⇒ ใส่คำต้องห้ามเข้าไปด้วย
 */
export function brandBriefBlock(opts: { forPublicCopy?: boolean } = {}): string {
  const lines: string[] = [
    '## Brand Brief — CEO AI Thailand (บริบทบังคับ ห้ามขัด)',
    '',
    `**บริษัท**: ${WHO.name} — ${WHO.oneLiner} · จุดยืน: ${WHO.positioning}`,
    `พัฒนาโดย ${WHO.parent} · ผสาน 2 เสา:`,
    ...WHO.pillars.map((p) => `  - ${p}`),
    'สิ่งที่เราไม่ใช่:',
    ...WHO.notThis.map((n) => `  - ${n}`),
    '',
    `**คุยกับใคร** (เรียงตามลำดับ ห้ามสลับ):`,
    `  หลัก: ${AUDIENCE.primary}`,
    `  รอง: ${AUDIENCE.secondary}`,
    `  ตลาดกว้าง: ${AUDIENCE.broad}`,
    `  ขั้นถัดไปของ Journey: ${AUDIENCE.growth}`,
    `  ประตูข้าง: ${AUDIENCE.sideDoor}`,
    `  🔴 persona: ${AUDIENCE.persona}`,
    `  ⚠️ ห้ามสับสน — ผู้ชมวันนี้ (Current Audience) ≠ ตลาดเป้าหมาย (Target Market)`,
    `     ผู้ชมวันนี้: ${AUDIENCE.currentAudience}`,
    `     ตลาดเป้าหมาย: ${AUDIENCE.targetMarket}`,
    `  เรื่องที่เขาสนใจจริง: ${AUDIENCE.caresAbout.join(' · ')}`,
    '',
    `**เส้นทางลูกค้า** (สารต้องตรงกับขั้นที่เขาอยู่):`,
    `  ${CUSTOMER_JOURNEY.map((j) => `${j.step}.${j.name}`).join(' → ')}`,
    `  🔴 ISO/SOP/KPI เริ่มมีความหมายที่ขั้น ${ISO_ENTERS_AT_STEP} — พูดกับคนขั้น 1–3 = พูดเรื่องที่เขายังไม่มีปัญหา`,
    '',
    strategyBlock(),
    '',
    `**ลำดับของสาร (ห้ามสลับ)**: นำด้วย → ${MESSAGE_HIERARCHY.lead}`,
    `  ตามด้วย (เฉพาะเมื่อรู้ว่าเขาอยู่กลุ่มไหนแล้ว) → ${MESSAGE_HIERARCHY.secondary}`,
    `  พูดมาตรฐานขึ้นหน้าได้เมื่อ: ${MESSAGE_HIERARCHY.isoLeadAllowedWhen}`,
    `  🔴 ทำไมห้ามสลับ: ${MESSAGE_HIERARCHY.whyNotSwap}`,
    '',
    `**ปัญหาของเขา**: ${PROBLEM.headline}`,
    ...PROBLEM.symptoms.map((s) => `  - ${s}`),
    `  จุดยืนที่ห้ามพูดกลับด้าน: ${PROBLEM.stance}`,
    '',
    `**ผลลัพธ์ที่สัญญา**: ${OUTCOME.promise}`,
    ...OUTCOME.concrete.map((c) => `  - ${c}`),
    `  ราคา: ${OUTCOME.pricing}`,
    '',
    '**น้ำเสียง — ทำ**:',
    ...VOICE.do.map((v) => `  - ${v}`),
    '**น้ำเสียง — ห้าม**:',
    ...VOICE.dont.map((v) => `  - ${v}`),
    '',
    '**สถานะจริงตอนนี้ (ห้ามเขียนขัดข้อนี้)**:',
    `  - ${HONEST_STATE.payingCustomers}`,
    `  - ${HONEST_STATE.reach}`,
    `  - ${HONEST_STATE.implication}`,
  ];
  if (opts.forPublicCopy) {
    lines.push(
      '',
      '**คำที่ห้ามปรากฏในข้อความที่คนนอกเห็น** (ระบบทำไม่ได้จริง):',
      ...FORBIDDEN_PHRASES.map((p) => `  - "${p}"`),
    );
  }
  return lines.join('\n');
}

/** ตรวจว่าข้อความที่ AI (หรือคน) เขียน ละเมิดคำต้องห้ามไหม — ใช้ก่อนปล่อยคอนเทนต์
 *  คืนรายการคำที่เจอ (ว่าง = ผ่าน) */
export function violatesBrand(text: string): string[] {
  const t = (text || '').replace(/\s+/g, ' ');
  return FORBIDDEN_PHRASES.filter((p) => t.includes(p));
}
