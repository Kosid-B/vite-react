/** ⑧ ประกอบเป็นบล็อกบริบทสำหรับแปะหน้า prompt
 *  = กล่อง "บริษัท/ปัญหา/ความต้องการ/ผลลัพธ์" ในแผนภาพ Brand Brief
 *
 *  @param opts.forPublicCopy true = กำลังจะเขียนข้อความที่คนนอกเห็น ⇒ ใส่คำต้องห้ามเข้าไปด้วย
 */
export function brandBriefBlock(opts: { forPublicCopy?: boolean } = {}): string {
  const lines: string[] = [
    '## Brand Brief — CEO AI Thailand (บริบทบังคับ ห้ามขัด)',
    '',
    `**บริษัท**: ${WHO.name} — ${WHO.oneLiner} · จุดยืน: ${WHO.positioning}`,
    `พัฒนาโดย ${WHO.parent} · ผสาน 2 เสา:`,
    ...WHO.pillars.map((p) => `  - ${p}`),
    'สิ่งที่เราไม่ใช่:',
    ...WHO.notThis.map((n) => `  - ${n}`),
    '',
    `**คุยกับใคร**: ${AUDIENCE.primary}`,
    `  (${AUDIENCE.evidence})`,
    `  รอง: ${AUDIENCE.secondary}`,
    `  เรื่องที่เขาสนใจจริง: ${AUDIENCE.caresAbout.join(' · ')}`,
    '',
    `**ปัญหาของเขา**: ${PROBLEM.headline}`,
    ...PROBLEM.symptoms.map((s) => `  - ${s}`),
    `  จุดยืนที่ห้ามพูดกลับด้าน: ${PROBLEM.stance}`,
    '',
    `**ผลลัพธ์ที่สัญญา**: ${OUTCOME.promise}`,
    ...OUTCOME.concrete.map((c) => `  - ${c}`),
    `  ราคา: ${OUTCOME.pricing}`,
    '',
    '**น้ำเสียง — ทำ**:',
    ...VOICE.do.map((v) => `  - ${v}`),
    '**น้ำเสียง — ห้าม**:',
    ...VOICE.dont.map((v) => `  - ${v}`),
    '',
    '**สถานะจริงตอนนี้ (ห้ามเขียนขัดข้อนี้)**:',
    `  - ${HONEST_STATE.payingCustomers}`,
    `  - ${HONEST_STATE.reach}`,
    `  - ${HONEST_STATE.implication}`,
  ];
  if (opts.forPublicCopy) {
    lines.push(
      '',
      '**คำที่ห้ามปรากฏในข้อความที่คนนอกเห็น** (ระบบทำไม่ได้จริง):',
      ...FORBIDDEN_PHRASES.map((p) => `  - "${p}"`),
    );
  }
  return lines.join('\n');
}

/** ตรวจว่าข้อความที่ AI (หรือคน) เขียน ละเมิดคำต้องห้ามไหม — ใช้ก่อนปล่อยคอนเทนต์
 *  คืนรายการคำที่เจอ (ว่าง = ผ่าน) */
export function violatesBrand(text: string): string[] {
  const t = (text || '').replace(/\s+/g, ' ');
  return FORBIDDEN_PHRASES.filter((p) => t.includes(p));
}
