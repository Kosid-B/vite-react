/** จำแนกประเภทร้านจากข้อความ (ชื่อ/หมวด/คำอธิบาย) */
export function shopKind(text: string): ShopKind {
  const c = (text ?? '').toLowerCase();
  for (const [kind, kws] of SHOP_KEYWORDS) if (kws.some(k => c.includes(k.toLowerCase()))) return kind;
  return 'other';
}

