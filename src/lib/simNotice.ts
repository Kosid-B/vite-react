/** เส้นตายที่ประกาศไว้ (ปีสากล — ตรงกับ 2569 ในบทความ) */
export const SIM_DEADLINE_ISO = '2026-08-30';

const HOUR = 3600_000;
const TH_OFFSET = 7 * HOUR;

/** หมดอายุตอน "สิ้นวันของเส้นตาย ตามเวลาไทย" ไม่ใช่เที่ยงคืน UTC
 *  (ถ้าใช้ UTC แถบจะหายตั้งแต่ 5 โมงเย็นของวันสุดท้าย = ตัดคนที่ยังทำไม่ทัน) */
export function simNoticeEndsAt(): number {
  return Date.parse(`${SIM_DEADLINE_ISO}T00:00:00Z`) + 24 * HOUR - TH_OFFSET - 1;
}

export function simNoticeActive(nowMs: number): boolean {
  return nowMs <= simNoticeEndsAt();
}

