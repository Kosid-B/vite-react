/** ตรวจสคริปต์ก่อนถ่าย — คืนรายการปัญหา (ว่าง = ผ่าน)
 *  ⚠️ ตรวจได้เฉพาะสิ่งที่ตรวจด้วยข้อความได้ · เรื่องจังหวะ/น้ำเสียงต้องใช้คนดู */
export function checkVideoScript(script: string): string[] {
  const issues: string[] = [];
  const t = (script || '').replace(/\s+/g, ' ');

  for (const p of FORBIDDEN_PHRASES) {
    if (t.includes(p)) issues.push(`🚫 มีคำต้องห้ามของแบรนด์: "${p}"`);
  }
  // ลิงก์ต้องไม่มาก่อนคำถามปิดท้าย
  const linkAt = t.search(/ceoaithailand\.org/);
  const qAt = t.lastIndexOf('?');
  if (linkAt >= 0 && qAt >= 0 && linkAt < qAt - 200) {
    issues.push('⚠️ ลิงก์โผล่ก่อนคำถามปิดท้ายนานเกินไป — ลิงก์ก่อน = โฆษณา');
  }
  if (/รีวิวจากลูกค้า|ลูกค้าของเราบอกว่า|เคสความสำเร็จของลูกค้า/.test(t)) {
    issues.push(`🚫 อ้างรีวิว/เคสลูกค้า — ${HONEST_STATE.payingCustomers}`);
  }
  if (/^\s*(สวัสดีครับ|สวัสดีค่ะ|ผมชื่อ|ดิฉันชื่อ)/.test(script.trim())) {
    issues.push('⚠️ ขึ้นต้นด้วยการทักทาย/แนะนำตัว — 3 วินาทีแรกเป็นของปัญหาเขา');
  }
  return issues;
}

