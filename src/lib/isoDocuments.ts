import { STANDARDS, type StandardId } from './isoStandards';

/** ประเภทเอกสารในระบบบริหาร — เรียงตามลำดับชั้นที่ใช้กันจริง */
export type DocType =
  | 'policy'      // นโยบาย — ผู้บริหารสูงสุดลงนาม
  | 'manual'      // คู่มือ/ขอบเขตระบบ
  | 'procedure'   // ระเบียบปฏิบัติ (SOP) — "ใครทำอะไร เมื่อไร"
  | 'wi'          // วิธีปฏิบัติงาน (WI) — "ทำอย่างไร ทีละขั้น"
  | 'form'        // แบบฟอร์ม — ของว่างที่รอกรอก
  | 'register'    // ทะเบียน/ตาราง — รายการที่ต้องคงไว้และอัปเดต
  | 'plan'        // แผน — มีกรอบเวลาและผู้รับผิดชอบ
  | 'record';     // บันทึก — หลักฐานว่าทำจริง (เกิดหลังใช้ฟอร์ม)

export const DOC_TYPE_LABEL: Record<DocType, string> = {
  policy: 'นโยบาย',
  manual: 'คู่มือ/ขอบเขต',
  procedure: 'ระเบียบปฏิบัติ (SOP)',
  wi: 'วิธีปฏิบัติงาน (WI)',
  form: 'แบบฟอร์ม',
  register: 'ทะเบียน/ตาราง',
  plan: 'แผน',
  record: 'บันทึก',
};

/** เดาประเภทเอกสารจากชื่อ — ใช้คำนำหน้าที่วงการใช้จริง
 *  เรียงลำดับสำคัญ: ตรวจคำที่เฉพาะเจาะจงก่อนคำกว้าง */
export function docTypeOf(name: string): DocType {
  const n = name.trim();
  if (/^นโยบาย/.test(n)) return 'policy';
  if (/คู่มือ|ขอบเขต/.test(n)) return 'manual';
  if (/^ระเบียบ|ขั้นตอนปฏิบัติงาน|^ขั้นตอน/.test(n)) return 'procedure';
  if (/วิธีปฏิบัติงาน|\bWI\b/i.test(n)) return 'wi';
  if (/^แผน/.test(n)) return 'plan';
  if (/ทะเบียน|^ตาราง|Matrix|Master List|^ผังองค์กร|^แผนผัง/i.test(n)) return 'register';
  if (/^บันทึก|^รายงาน/.test(n)) return 'record';
  if (/แบบฟอร์ม|^ฟอร์ม/.test(n)) return 'form';
  return 'record'; // ค่าเริ่มต้นปลอดภัยสุด — บันทึกคือสิ่งที่ผู้ตรวจขอดูเสมอ
}

export interface DocNeed {
  /** ชื่อเอกสารตามที่ผู้ตรวจเรียก */
  name: string;
  type: DocType;
  /** ข้อกำหนดที่เอกสารนี้ตอบ — เอกสารหนึ่งฉบับมักตอบได้หลายข้อ */
  clauses: string[];
  /** มีข้อใดข้อหนึ่งที่มาตรฐานกำหนดให้ต้องมีเอกสารหรือไม่ */
  mandatory: boolean;
  /** ลำดับความสำคัญที่สูงที่สุดในบรรดาข้อที่เกี่ยว (1 = ผู้ตรวจดูแน่) */
  priority: 1 | 2 | 3;
}

/** แยกชื่อเอกสารหลายฉบับที่เขียนรวมกันด้วย " + " ใน keyDoc */
function splitDocs(keyDoc: string): string[] {
  return keyDoc.split('+').map((s) => s.trim()).filter(Boolean);
}

/** ทะเบียนเอกสารที่ต้องมีของมาตรฐานหนึ่ง — รวมเอกสารซ้ำเข้าด้วยกัน
 *
 *  จุดสำคัญ: เอกสารฉบับเดียวมักตอบได้หลายข้อกำหนด การรวมให้เห็นภาพนี้
 *  คือสิ่งที่ทำให้จำนวนเอกสารลดลงจริง — และเป็นเหตุผลที่ระบบของหลายที่บวมเกินจำเป็น
 *  (ทำเอกสารแยกทีละข้อ ทั้งที่ฉบับเดียวครอบคลุมได้)
 *
 *  เรียงผลลัพธ์: บังคับก่อน → priority สูงก่อน → ตอบหลายข้อก่อน */
export function documentRegister(std: StandardId): DocNeed[] {
  const byName = new Map<string, DocNeed>();

  for (const c of STANDARDS[std].clauses) {
    for (const name of splitDocs(c.guide.keyDoc)) {
      const cur = byName.get(name);
      if (cur) {
        cur.clauses.push(c.id);
        cur.mandatory = cur.mandatory || c.guide.mandatoryDoc === true;
        cur.priority = Math.min(cur.priority, c.guide.priority) as 1 | 2 | 3;
      } else {
        byName.set(name, {
          name,
          type: docTypeOf(name),
          clauses: [c.id],
          mandatory: c.guide.mandatoryDoc === true,
          priority: c.guide.priority,
        });
      }
    }
  }

  return [...byName.values()].sort(
    (a, b) =>
      Number(b.mandatory) - Number(a.mandatory) ||
      a.priority - b.priority ||
      b.clauses.length - a.clauses.length ||
      a.name.localeCompare(b.name, 'th'),
  );
}

export interface RegisterStats {
  total: number;
  mandatory: number;
  /** เอกสารที่ตอบได้ตั้งแต่ 2 ข้อขึ้นไป — จุดที่ประหยัดแรงได้มากที่สุด */
  multiClause: number;
  byType: Record<DocType, number>;
}

export function registerStats(docs: readonly DocNeed[]): RegisterStats {
  const byType = {} as Record<DocType, number>;
  for (const k of Object.keys(DOC_TYPE_LABEL) as DocType[]) byType[k] = 0;
  for (const d of docs) byType[d.type]++;
  return {
    total: docs.length,
    mandatory: docs.filter((d) => d.mandatory).length,
    multiClause: docs.filter((d) => d.clauses.length >= 2).length,
    byType,
  };
}

