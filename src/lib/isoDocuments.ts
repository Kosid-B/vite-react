/* ══════════════════════════════════════════════════════════════════════
 * บริบทลูกค้า — สิ่งที่ทำให้เอกสารไม่เป็น "ของทั่วไป"
 * ยิ่งกรอกครบ ร่างยิ่งใช้ได้จริง · เว้นว่างได้ แต่ผลจะกว้างขึ้น
 * ══════════════════════════════════════════════════════════════════════ */
export interface ClientContext {
  company?: string;
  industry?: string;      // เช่น 'ผลิตชิ้นส่วนยานยนต์'
  employees?: number;
  scope?: string;         // ขอบเขตที่จะขอรับรอง
  processes?: string[];   // กระบวนการหลัก
  /** สิ่งที่มีอยู่แล้ว — กันไม่ให้ร่างของซ้ำกับที่ลูกค้าทำไว้ */
  existingDocs?: string[];
  /** ข้อจำกัดจริง เช่น 'ไม่มีฝ่าย QA แยก' 'พนักงานอ่านเอกสารยาวไม่ไหว' */
  constraints?: string;
}

/** ประกอบ prompt ให้ AI ร่างเอกสารหนึ่งฉบับ — pure จึงทดสอบได้ว่าใส่ครบไหม
 *
 *  ข้อบังคับที่ฝังใน prompt (สำคัญกว่าตัวเนื้อหา):
 *    • ห้ามแต่งตัวเลข ชื่อคน หรือข้อเท็จจริงที่ไม่ได้ให้มา — ให้เว้น [ ] ไว้แทน
 *    • ห้ามอ้างข้อกำหนดที่ไม่ได้ระบุในโจทย์
 *    • ต้องใช้โครงตามที่กำหนด ห้ามเพิ่ม/ลด/สลับหัวข้อ
 *  สามข้อนี้คือเส้นแบ่งระหว่าง "ร่างที่ที่ปรึกษาตรวจแล้วส่งได้" กับ "ของที่ต้องเขียนใหม่ทั้งฉบับ" */
export function draftPrompt(std: StandardId, doc: DocNeed, ctx: ClientContext = {}): string {
  const s = STANDARDS[std];
  const clauseLines = doc.clauses
    .map((id) => {
      const c = s.clauses.find((x) => x.id === id);
      return c ? `- ข้อ ${c.id} ${c.title}: ${c.guide.action}` : `- ข้อ ${id}`;
    })
    .join('\n');

  const ctxLines = [
    ctx.company && `ชื่อองค์กร: ${ctx.company}`,
    ctx.industry && `ประเภทธุรกิจ: ${ctx.industry}`,
    ctx.employees != null && `จำนวนพนักงาน: ${ctx.employees}`,
    ctx.scope && `ขอบเขตที่จะขอรับรอง: ${ctx.scope}`,
    ctx.processes?.length && `กระบวนการหลัก: ${ctx.processes.join(', ')}`,
    ctx.existingDocs?.length && `เอกสารที่มีอยู่แล้ว (ห้ามร่างซ้ำ ให้อ้างอิงแทน): ${ctx.existingDocs.join(', ')}`,
    ctx.constraints && `ข้อจำกัดที่ต้องคำนึง: ${ctx.constraints}`,
  ]
    .filter(Boolean)
    .join('\n');

  return [
    `คุณคือผู้ช่วยของที่ปรึกษาระบบบริหารที่มีประสบการณ์ 20 ปี`,
    `หน้าที่ของคุณคือร่างเอกสารตามโครงที่กำหนด เพื่อให้ที่ปรึกษานำไปตรวจและแก้ต่อ`,
    `ไม่ใช่การส่งมอบเอกสารฉบับสมบูรณ์ให้ลูกค้าโดยตรง`,
    ``,
    `มาตรฐาน: ${s.code}`,
    `เอกสารที่ต้องร่าง: ${doc.name} (${DOC_TYPE_LABEL[doc.type]})`,
    doc.mandatory ? `สถานะ: เป็นเอกสารที่มาตรฐานกำหนดให้ต้องมี` : `สถานะ: ไม่ได้บังคับ แต่ผู้ตรวจมักขอดู`,
    ``,
    `ข้อกำหนดที่เอกสารนี้ต้องตอบ:`,
    clauseLines,
    ``,
    ctxLines ? `บริบทของลูกค้า:\n${ctxLines}` : `บริบทของลูกค้า: ยังไม่ระบุ — ให้เว้นวงเล็บเหลี่ยมไว้ทุกจุดที่ต้องใช้ข้อมูลเฉพาะ`,
    ``,
    `โครงที่ต้องใช้ (ห้ามเพิ่ม ลด หรือสลับลำดับหัวข้อ):`,
    DOC_SKELETON[doc.type].map((x) => `- ${x}`).join('\n'),
    ``,
    `ข้อบังคับ:`,
    `1. ห้ามแต่งตัวเลข ชื่อบุคคล ชื่อหน่วยงาน หรือข้อเท็จจริงที่ไม่ได้ให้มา — ให้ใส่ [ระบุ...] ไว้แทน`,
    `2. ห้ามอ้างอิงข้อกำหนดอื่นนอกจากที่ระบุไว้ข้างต้น`,
    `3. เขียนให้คนหน้างานอ่านแล้วทำตามได้ ไม่ใช่เขียนให้ผ่านการตรวจอย่างเดียว`,
    `4. ถ้าข้อมูลไม่พอจนร่างส่วนใดไม่ได้ ให้เขียนว่าต้องการข้อมูลอะไรเพิ่ม แทนการเดา`,
    `5. ภาษาไทย กระชับ หลีกเลี่ยงประโยคยาวและศัพท์ที่ไม่จำเป็น`,
  ]
    .filter((x) => x !== undefined)
    .join('\n');
}
