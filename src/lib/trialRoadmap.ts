/** ขั้นถัดไปที่ควรทำ จากหน้าที่ผู้ใช้เคยเข้าแล้ว — ใช้ในแอปเพื่อพาเดินต่อ
 *  คืน null เมื่อเดินครบทุกขั้นแล้ว */
export function nextStep(visitedPages: readonly string[]): RoadmapStep | null {
  return TRIAL_ROADMAP.find((s) => !visitedPages.includes(s.page)) ?? null;
}

/** ความคืบหน้า 0–100 — นับจากขั้นที่ผู้ใช้เคยเปิดหน้านั้นแล้วจริง */
export function roadmapProgress(visitedPages: readonly string[]): number {
  const done = TRIAL_ROADMAP.filter((s) => visitedPages.includes(s.page)).length;
  return Math.round((done / TRIAL_ROADMAP.length) * 100);
}

