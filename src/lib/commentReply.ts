/* ── อ่านตัวเลขจากคอมเมนต์ที่คนพิมพ์กันจริง ───────────────────────────── */

export interface ParsedNumbers {
  price: number;
  cost: number;
  /** ⚠️ ต้นทุนมากกว่าราคา — อาจพิมพ์สลับ ต้องถามกลับ ไม่ใช่คำนวณให้เลย */
  suspectSwapped: boolean;
}

/** แปลงเลขไทย ๐-๙ เป็นเลขอารบิก (บางคนพิมพ์เลขไทย) */
function thaiDigits(s: string): string {
  const map: Record<string, string> = { '๐': '0', '๑': '1', '๒': '2', '๓': '3', '๔': '4', '๕': '5', '๖': '6', '๗': '7', '๘': '8', '๙': '9' };
  return s.replace(/[๐-๙]/g, (d) => map[d] ?? d);
}

/** ดึงตัวเลข 2 ตัวแรกจากคอมเมนต์ — รองรับรูปแบบที่คนพิมพ์จริง
 *  "50/30" · "50 30" · "ขาย 50 ทุน 30" · "ราคา 1,500 ต้นทุน 900" · "๕๐/๓๐"
 *  คืน null เมื่อหาไม่เจอ 2 ตัว (ห้ามเดา — ตอบผิดในที่สาธารณะเสียหายกว่าไม่ตอบ) */
export function parseNumbers(text: string): ParsedNumbers | null {
  // ⚠️ ลบเฉพาะจุลภาคที่คั่นหลักพัน (มีตัวเลขขนาบสองข้าง) — ห้ามแทนด้วยช่องว่าง
  //    เคยพลาดจริง: "1,500" กลายเป็น "1 500" → อ่านได้ราคา 1 ต้นทุน 500 แล้วตอบผิดในที่สาธารณะ
  //    ส่วน "50, 30" (จุลภาคคั่นค่า มีช่องว่างตาม) ไม่โดนลบ จึงยังแยกเป็นสองตัวได้ถูก
  const t = thaiDigits(text || '').replace(/(?<=\d),(?=\d)/g, '');
  // ยอมทศนิยม · ตัดตัวเลขที่ติดกับ % ทิ้ง (เช่น "ลด 10%") เพราะไม่ใช่ราคา
  const nums = (t.match(/\d+(?:\.\d+)?%?/g) ?? [])
    .filter((n) => !n.endsWith('%'))
    .map(Number)
    .filter((n) => Number.isFinite(n) && n > 0);
  if (nums.length < 2) return null;
  const [a, b] = nums;
  return { price: a, cost: b, suspectSwapped: b > a };
}

/* ── สร้างข้อความตอบกลับ ─────────────────────────────────────────────── */

export type ReplyChannel = 'comment' | 'dm' | 'tiktok';

const baht = (n: number) => n.toLocaleString('th-TH', { maximumFractionDigits: 2 });

/** ข้อความเมื่ออ่านตัวเลขไม่ออก — ถามกลับให้ง่ายที่สุด ไม่ตำหนิ */
export const REPLY_NEED_NUMBERS =
  'ขอ 2 ตัวเลขครับ — ราคาขายต่อชิ้น กับ ต้นทุนต่อชิ้น พิมพ์แบบนี้ก็ได้ครับ: 50/30 แล้วเดี๋ยวผมคำนวณให้';

/** ข้อความเมื่อต้นทุนมากกว่าราคา — ถามกลับ ไม่ด่วนสรุปว่าเขาขาดทุน */
export function replySwapped(p: ParsedNumbers): string {
  return (
    `ขอเช็คก่อนครับ — ${baht(p.price)} คือราคาขาย และ ${baht(p.cost)} คือต้นทุนใช่ไหมครับ? ` +
    'ถ้าสลับกันบอกได้เลย เดี๋ยวคำนวณให้ใหม่'
  );
}

export interface ReplyOptions {
  channel: ReplyChannel;
  /** ลิงก์สั้นสำหรับส่งในแชท (ห้ามใส่ในคอมเมนต์ — เฟซบุ๊กกดการมองเห็นโพสต์ที่มีลิงก์) */
  link?: string;
}

/**
 * สร้างคำตอบจากตัวเลขที่เขาพิมพ์มา
 *
 * ⚠️ กติกา (มีเทสต์บังคับ):
 *   - ทุกตัวเลขในคำตอบต้องคำนวณจาก price/cost ที่เขาให้มาเท่านั้น
 *   - ห้ามมีลิงก์ในคำตอบช่อง 'comment' (ลดการมองเห็น — ดู skill social-creative-linking)
 *   - ห้ามสัญญาผลลัพธ์ทางธุรกิจ · ห้ามอ้างค่าเฉลี่ยตลาดที่เราไม่มี
 */
export function buildReply(p: ParsedNumbers, opts: ReplyOptions): string {
  if (p.suspectSwapped) return replySwapped(p);

  const input: ProductInput = { biz: 'all', price: p.price, cost: p.cost };
  const margin = p.price - p.cost;
  const up = priceScenario(input, 10);
  const down = priceScenario(input, -10);

  const lines: string[] = [];
  lines.push(`ราคา ${baht(p.price)} ต้นทุน ${baht(p.cost)} → กำไรต่อชิ้น ${baht(margin)} บาท (${Math.round((margin / p.price) * 100)}%)`);
  lines.push('');

  if (up.breakEvenVolumePct != null) {
    lines.push(`📈 ขึ้นราคา 10% เป็น ${baht(up.newPrice)} บาท — เสียลูกค้าได้ถึง ${baht(up.breakEvenVolumePct)}% กำไรยังเท่าเดิม`);
  }
  if (down.breakEvenVolumePct != null) {
    lines.push(`📉 ลดราคา 10% เหลือ ${baht(down.newPrice)} บาท — ต้องขายเพิ่มอีก ${baht(Math.abs(down.breakEvenVolumePct))}% ถึงจะเท่าเดิม`);
  } else if (down.belowCost) {
    lines.push(`📉 ลดราคา 10% เหลือ ${baht(down.newPrice)} บาท — ต่ำกว่าต้นทุนแล้ว ทำไม่ได้ครับ`);
  }

  lines.push('');
  lines.push('เป็นเลขคณิตล้วนจากตัวเลขที่คุณให้มา ไม่ใช่ค่าเฉลี่ยของใคร');

  if (opts.channel === 'tiktok') {
    // TikTok: ลิงก์ในคอมเมนต์กดไม่ได้ คนต้อง "พิมพ์ตาม" → ต้องสั้นและเป็นคำไทยที่จำได้จากการเห็นครั้งเดียว
    // และคอมเมนต์อยู่ใต้คลิปเลย ไม่ต้องเข้าโปรไฟล์ = ข้ามคอขวดที่วัดได้จริง (15,900 วิว เข้าโปรไฟล์ 11 คน)
    lines.push('ตารางเต็มอยู่ที่ ceoaithailand.org/ราคา (พิมพ์ตามได้เลย ไม่ต้องสมัคร)');
  } else if (opts.channel === 'comment') {
    // ห้ามใส่ลิงก์ — ให้จบในเฟซบุ๊ก แล้วดึงเข้าแชทแทน
    lines.push('ถ้าอยากได้ตารางเต็ม (ขึ้น/ลด 10% และ 20% พร้อมจุดคุ้มทุนต่อเดือน) ทักแชทมาได้เลยครับ');
  } else {
    lines.push('ตารางเต็ม + เครื่องคิดของคุณเองอยู่ที่นี่ครับ' + (opts.link ? ` ${opts.link}` : ''));
  }
  return lines.join('\n');
}

/* ── โพสต์แบบ "คอมเมนต์คำเดียวแล้วส่งลิงก์ให้" ───────────────────────────
 * ทำไมไม่ใส่ลิงก์ในโพสต์: เฟซบุ๊กลดการมองเห็นโพสต์ที่พาคนออกนอกแพลตฟอร์ม
 * ให้คนคอมเมนต์คำเดียว → คอมเมนต์ = สัญญาณ engagement → เราทักกลับพร้อมลิงก์
 * ─────────────────────────────────────────────────────────────────────── */

export interface KeywordOffer {
  /** คำที่ให้คนพิมพ์ — ต้องสั้น พิมพ์ง่าย ไม่ต้องสลับแป้น */
  keyword: string;
  /** สิ่งที่เขาจะได้ — ต้องมีอยู่จริงในระบบแล้ว */
  gives: string;
  /** ลิงก์สั้นที่จะส่งให้ในแชท (ต้องมีใน SHORT_LINKS จริง) */
  shortLink: string;
  /** true = โฟกัสรอบนี้ (Gen X/Y/Z + SME ที่กำลังเริ่ม/ทำธุรกิจ)
   *  false = ของดีแต่คนละจังหวะ เก็บไว้รอบถัดไป ไม่ใช่ทิ้ง
   *  เหตุผลที่ต้องมีธงนี้: โพสต์พร้อมกันหมด = ไม่รู้ว่าคำไหนได้ผล
   *  (บทเรียนเดียวกับที่เคยสรุปผิดจากกลุ่มตัวอย่างเล็ก — LESSONS-LEDGER ข้อ 1) */
  focus: boolean;
}

