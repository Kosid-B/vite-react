/** ตอนจบคลิปแบบ "ค้าง" ไม่ใช่ "อิ่ม"
 *
 * ทำไมต้องมี (วัดได้จริง 16 ส.ค. 2569): คลิปหนึ่งมีคนดูจบ 89% แต่ผู้ติดตาม 0
 * และแทบไม่มีใครกดออกไปเว็บ — ตอนจบให้คำตอบครบจนคนไม่ต้องไปไหนต่อ
 * แก้ด้วยการปิดด้วย "คำถามที่เขาตอบเองไม่ได้ถ้าไม่รู้ตัวเลขของตัวเอง"
 *   → ความอยากรู้มาจากธุรกิจเขา ไม่ใช่จากคำโฆษณาของเรา
 *
 * ⚠️ ไม่ใช่ clickbait: คำถามทุกข้อผูกกับ FAQ จริงในบทความปลายทาง (answeredBy)
 *    และมีเทสต์บังคับว่าต้องมีอยู่จริง — กดเข้าไปแล้วต้องเจอคำตอบเสมอ
 */
export function videoEnding(t: VideoTopic, origin = 'ceoaithailand.org'): {
  spoken: string; onScreen: string; pinned: string;
} {
  return {
    // พูดปิดคลิป — คำถามก่อน ลิงก์ทีหลังเสมอ (ลิงก์ก่อน = โฆษณา, คำถามก่อน = บทสนทนา)
    // ⚠️ ห้ามบรรยายรูปแบบของปลายทางเอง (เช่น "ผมทำตารางไว้ให้") — บทความบางตัวไม่มีตาราง
    //    ใช้ t.gives ซึ่งเป็นคำสัญญาที่ผูกกับบทความรายตัวและมีเทสต์คุมอยู่แล้ว
    spoken: `${t.openLoop} — ${t.gives} อยู่ในลิงก์ใต้คลิป อ่านฟรี ไม่ต้องสมัคร`,
    // ข้อความบนจอตอนท้าย — สั้นพอให้อ่านทันใน 2 วินาที
    onScreen: `${t.openLoop}\n👉 ${origin}${t.shortLink}`,
    // คอมเมนต์ปักหมุด — ทวนคำถามเดิมเพื่อให้คนที่เลื่อนผ่านยังเห็นช่องว่างนั้น
    pinned: `${t.openLoop}\n${t.gives} 👉 ${origin}${t.shortLink}?s=ytc&seg=${t.seg} (ฟรี ไม่ต้องสมัคร)`,
  };
}

